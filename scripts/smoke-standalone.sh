#!/usr/bin/env bash
# Prove an OpenSwarm standalone bundle works, without touching the operator.
#
#   bash scripts/smoke-standalone.sh <bundle-dir>
#
# <bundle-dir> is a bundle from scripts/build-standalone.sh, or the `current`
# symlink scripts/deploy-standalone.sh maintains. Exit 0 only when all hold:
#
#   1. bin/openswarm --version prints the bundle's VERSION while a decoy `node`
#      that exits 97 is first on PATH (the launcher must use the bundled node);
#   2. the bundled runtime loads the native modules better-sqlite3 and
#      @lancedb/lancedb and uses them (an in-memory query, a one-row table);
#   3. the daemon started from the bundle answers GET /api/health with the
#      bundle's version within 90 s, and stops on SIGTERM.
#
# Inertness. The daemon this boots must not act on anything real:
#   - every command runs under `env -i`: no tracker, chat, model or cloud
#     credential from the caller's environment (a login shell exports some);
#   - HOME and the working directory are fresh directories, so no operator
#     state (~/.openswarm, ~/.config/openswarm, ~/.codex) and no config.* in
#     the caller's directory is found;
#   - OPENSWARM_CONFIG names a generated config with no tracker or chat block,
#     no autonomous section (so no runner starts at all), no GitHub repos and
#     one disabled agent on an empty directory;
#   - OPENSWARM_TELEMETRY=0 and DO_NOT_TRACK=1, so no install id is registered;
#   - OPENSWARM_WEB_PORT is a free port other than 3847, so the operator's
#     daemon (if any) is neither probed as a duplicate nor disturbed;
#   - the daemon is stopped by its own pid only; nothing is matched by name.
#
# Scratch space lives next to the bundle (<bundle>/../.smoke-*), not in /tmp,
# which is tmpfs on some hosts, and is removed on exit.

set -euo pipefail

die() { echo "smoke-standalone: FAIL: $*" >&2; exit 1; }
log() { echo "smoke-standalone: $*"; }

[ $# -eq 1 ] || die "usage: smoke-standalone.sh <bundle-dir>"
[ -d "$1" ] || die "no bundle directory at $1"
BUNDLE="$(cd "$1" && pwd -P)"
LAUNCHER="$BUNDLE/bin/openswarm"
BUNDLED_NODE="$BUNDLE/node/bin/node"
[ -x "$LAUNCHER" ] || die "missing launcher $LAUNCHER"
[ -x "$BUNDLED_NODE" ] || die "missing bundled runtime $BUNDLED_NODE"
[ -f "$BUNDLE/VERSION" ] || die "missing $BUNDLE/VERSION"
VERSION="$(tr -d '[:space:]' < "$BUNDLE/VERSION")"
[ -n "$VERSION" ] || die "empty VERSION"

SCRATCH="$(cd "$BUNDLE/.." && pwd -P)/.smoke-$$"
DAEMON_PID=""
cleanup() {
  if [ -n "$DAEMON_PID" ] && kill -0 "$DAEMON_PID" 2>/dev/null; then
    kill -TERM "$DAEMON_PID" 2>/dev/null || true
    for _ in $(seq 1 20); do kill -0 "$DAEMON_PID" 2>/dev/null || break; sleep 0.5; done
    kill -KILL "$DAEMON_PID" 2>/dev/null || true
  fi
  rm -rf "$SCRATCH"
}
trap cleanup EXIT
mkdir -p "$SCRATCH/home" "$SCRATCH/cwd" "$SCRATCH/decoy" "$SCRATCH/project"

# A `node` that fails loudly, first on PATH: the launcher must not reach it.
printf '#!/bin/sh\necho "decoy node was run" >&2\nexit 97\n' > "$SCRATCH/decoy/node"
chmod 0755 "$SCRATCH/decoy/node"

cat > "$SCRATCH/config.yaml" <<EOF
# Generated by scripts/smoke-standalone.sh: an inert daemon for a health probe.
adapter: codex-responses
language: en
telemetry:
  enabled: false
agents:
  - name: smoke
    projectPath: $SCRATCH/project
    enabled: false
EOF

PORT="$("$BUNDLED_NODE" -e '
  const net = require("node:net");
  const tryPort = () => {
    const s = net.createServer();
    s.listen(0, "127.0.0.1", () => {
      const { port } = s.address();
      s.close(() => (port === 3847 ? tryPort() : console.log(port)));
    });
  };
  tryPort();
')"
[ -n "$PORT" ] && [ "$PORT" != 3847 ] || die "could not pick a free port"

# Run a command with nothing inherited but what is listed here.
inert() {
  (cd "$SCRATCH/cwd" && env -i \
    HOME="$SCRATCH/home" \
    PATH="$SCRATCH/decoy:/usr/bin:/bin" \
    LANG=C.UTF-8 \
    OPENSWARM_TELEMETRY=0 \
    DO_NOT_TRACK=1 \
    OPENSWARM_NO_AUTO_UPDATE=1 \
    NO_UPDATE_NOTIFIER=1 \
    OPENSWARM_CONFIG="$SCRATCH/config.yaml" \
    OPENSWARM_WEB_PORT="$PORT" \
    "$@")
}

# 1. Version through the launcher, with the decoy node first on PATH.
GOT="$(inert "$LAUNCHER" --version 2>&1)" || die "bin/openswarm --version failed: $GOT"
[ "$GOT" = "$VERSION" ] || die "bin/openswarm --version printed '$GOT', VERSION is '$VERSION'"
log "version $GOT (decoy node on PATH was not used)"

# 2. Native modules under the bundled runtime.
NATIVE="$(inert "$BUNDLED_NODE" --input-type=module -e '
  import { createRequire } from "node:module";
  const app = process.argv[1];
  const require = createRequire(app + "/package.json");
  const Database = require("better-sqlite3");
  const db = new Database(":memory:");
  const sqlite = db.prepare("select sqlite_version() as v").get().v;
  db.close();
  const lancedb = await import(require.resolve("@lancedb/lancedb"));
  const conn = await lancedb.connect(process.env.HOME + "/lance");
  const table = await conn.createTable("smoke", [{ id: 1, vector: [0.1, 0.2] }]);
  const rows = await table.countRows();
  if (rows !== 1) throw new Error("lancedb counted " + rows + " rows");
  console.log("better-sqlite3 " + sqlite + ", @lancedb/lancedb ok");
' "$BUNDLE/app" 2>&1)" || die "native modules did not load: $NATIVE"
log "$NATIVE"

# 3. The daemon from the bundle, inert, on its own port.
inert "$BUNDLED_NODE" "$BUNDLE/app/dist/index.js" > "$SCRATCH/daemon.log" 2>&1 &
DAEMON_PID=$!
HEALTH=""
for _ in $(seq 1 180); do
  if HEALTH="$(curl -fsS -m 2 "http://127.0.0.1:$PORT/api/health" 2>/dev/null)"; then break; fi
  HEALTH=""
  kill -0 "$DAEMON_PID" 2>/dev/null || break
  sleep 0.5
done
if [ -z "$HEALTH" ]; then
  tail -n 40 "$SCRATCH/daemon.log" >&2 || true
  die "daemon gave no /api/health answer on port $PORT within 90 s"
fi
HEALTH_VERSION="$(printf '%s' "$HEALTH" | inert "$BUNDLED_NODE" -e '
  let s = ""; process.stdin.on("data", (d) => (s += d)).on("end", () => {
    const h = JSON.parse(s);
    console.log(h.status === "ok" ? String(h.backend_version) : "status=" + h.status);
  });
')"
[ "$HEALTH_VERSION" = "$VERSION" ] || die "/api/health reported '$HEALTH_VERSION', VERSION is '$VERSION'"
log "daemon on 127.0.0.1:$PORT answered /api/health with $HEALTH_VERSION"

kill -TERM "$DAEMON_PID"
for _ in $(seq 1 30); do kill -0 "$DAEMON_PID" 2>/dev/null || break; sleep 0.5; done
if kill -0 "$DAEMON_PID" 2>/dev/null; then die "daemon pid $DAEMON_PID did not stop within 15 s of SIGTERM"; fi
DAEMON_PID=""
log "daemon stopped; bundle $BUNDLE is good"
